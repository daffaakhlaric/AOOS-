"use client";

import Link from "next/link";
import { useState } from "react";

import { formatRelativeTimeId } from "@/lib/formatters";

import styles from "./SamanthaDigest.module.css";

const TRUNCATE_LENGTH = 80;

export interface SamanthaDigestTag {
  readonly label: string;
  readonly tone: "pause" | "scale" | "fix";
}

export interface SamanthaDigestProps {
  readonly text: string;
  /** PAUSE/SCALE/FIX ad-count pills (FINAL UI REBUILD — reference screenshot's "3 perlu PAUSE /
   * 1 perlu SCALE / 8 perlu FIX" row). Optional so callers with no cached Meta data (nothing to
   * count yet) can omit it entirely rather than showing empty/zero pills. */
  readonly tags?: readonly SamanthaDigestTag[];
  /** "Lihat Strategi & Approve →" link target — real route (`/meta-ads/strategi`), passed by the
   * caller rather than hardcoded here so this component stays reusable/testable in isolation. */
  readonly strategiHref?: string;
  /** ISO timestamp of the cached Meta pull this digest was computed from (real bug fix: the
   * reference mockup shows a fixed "Hari ini 06:00 WIB", but this digest is actually recomputed
   * from whatever `/meta-ads` snapshot is cached — there is no real scheduled-06:00 generation
   * job, so showing the real cache timestamp here instead of a fabricated fixed time). */
  readonly updatedAt?: string;
}

const TAG_ICON: Readonly<Record<SamanthaDigestTag["tone"], string>> = {
  pause: "⏸",
  scale: "↗",
  fix: "🔧",
};

/**
 * Latest Samantha daily digest (FINAL UI REBUILD, reference screenshot: summary text + PAUSE/SCALE/
 * FIX tag pills + "Lihat Strategi & Approve →" link). Rule-based, computed by `DashboardClient.tsx`
 * from the SAME cached `/meta-ads` pull `MetaAdsClient`/`AnalisaClient` already read via
 * `readCampaignsCache()` — never a live Meta API call, and never text generated by an LLM (no
 * `aaos-api` "daily digest" endpoint exists), just a formatted summary of real per-ad `verdict`/
 * `spend`/`rphD3` numbers already on hand.
 */
export function SamanthaDigest({
  text,
  tags,
  strategiHref,
  updatedAt,
}: SamanthaDigestProps): React.ReactElement {
  const [expanded, setExpanded] = useState(false);
  const isLong = text.length > TRUNCATE_LENGTH;
  const shown = expanded || !isLong ? text : `${text.slice(0, TRUNCATE_LENGTH)}...`;

  return (
    <section data-testid="samantha-digest" className={styles.section}>
      <div className={styles.header}>
        <p className={styles.title}>✨ Samantha Daily Digest</p>
        {updatedAt !== undefined ? (
          <span className={styles.updatedAt}>Diperbarui {formatRelativeTimeId(updatedAt)}</span>
        ) : null}
      </div>
      <p className={styles.text}>{shown}</p>
      {isLong ? (
        <button
          type="button"
          onClick={() => setExpanded((current) => !current)}
          className={styles.toggle}
        >
          {expanded ? "Sembunyikan" : "Lihat selengkapnya"}
        </button>
      ) : null}
      {(tags !== undefined && tags.length > 0) || strategiHref !== undefined ? (
        <div className={styles.footer}>
          <div className={styles.tags}>
            {(tags ?? []).map((tag) => (
              <span key={tag.label} className={`${styles.tag} ${styles[tag.tone] ?? ""}`}>
                <span aria-hidden="true">{TAG_ICON[tag.tone]}</span> {tag.label}
              </span>
            ))}
          </div>
          {strategiHref !== undefined ? (
            <Link href={strategiHref} className={styles.link}>
              Lihat Strategi &amp; Approve →
            </Link>
          ) : null}
        </div>
      ) : null}
    </section>
  );
}
