import type { SupabaseClientLike } from "@aos/lead-store";

const TABLE = "loop_runs";

/** Raw `loop_runs` row shape (snake_case) — COLUMN-FOR-COLUMN with `supabase/migrations/048_campaign_auto_publish.sql`. */
export interface LoopRunRow {
  readonly id: string;
  readonly tenant_id: string;
  readonly started_at: string;
  readonly completed_at: string | null;
  readonly duration_ms: number | null;
  readonly correlation_id?: string;
  readonly status?: string;
  readonly current_stage?: string;
  readonly error_code?: string | null;
  readonly total_verdicts: number;
  readonly total_briefs_auto_generated: number;
  readonly total_assets_generated: number;
  readonly total_campaigns_published: number;
  readonly created_at: string;
}

export interface CreateLoopRunInput {
  readonly id: string;
  readonly tenantId: string;
  readonly startedAt: string;
  readonly completedAt: string;
  readonly durationMs: number;
  readonly totalVerdicts: number;
  readonly totalBriefsAutoGenerated: number;
  readonly totalAssetsGenerated: number;
  readonly totalCampaignsPublished: number;
}

export class LoopRunRepositoryError extends Error {}

/**
 * Supabase-backed persistence for `loop_runs` (AAOS LOOP UPGRADE, Sprint 8c — Prompt 19 Step 6). Same
 * shared `SupabaseClientLike` port + `SUPABASE_CLIENT` DI token every other `aaos-api` repository
 * uses — mirrors `AuditLogRepository`'s exact shape.
 *
 * `insert()` is deliberately best-effort at the CALLER (`SchedulerService.runPropertyCampaignTriggerCheck`),
 * not inside this repository itself — unlike `AuditLogService.record`, a `loop_runs` summary row is
 * the ONE user-visible artifact Step 6 exists to produce, so its caller decides explicitly whether a
 * failure here should be logged-and-swallowed (matches this dispatch's own "never let a side-check
 * take down the whole handler" discipline) rather than this repository silently deciding that for
 * every caller.
 */
export class LoopRunRepository {
  constructor(private readonly client: SupabaseClientLike) {}

  async insert(input: CreateLoopRunInput): Promise<LoopRunRow> {
    if (process.env["ADVERTISING_LOOP_RUNTIME_V2"] === "true") {
      // The runtime already created this exact correlation row before the handler started.
      // Keep the lease and completion exclusively owned by the runtime RPC.
      const result = await this.client
        .from<LoopRunRow>(TABLE)
        .update({
          total_verdicts: input.totalVerdicts,
          total_briefs_auto_generated: input.totalBriefsAutoGenerated,
          total_assets_generated: input.totalAssetsGenerated,
          total_campaigns_published: input.totalCampaignsPublished,
        })
        .eq("id", input.id)
        .eq("tenant_id", input.tenantId)
        .eq("status", "RUNNING")
        .select("*")
        .single();
      if (result.error || !result.data)
        throw new LoopRunRepositoryError("Active loop summary could not be persisted");
      return result.data;
    }
    const { data, error } = await this.client
      .from<LoopRunRow>(TABLE)
      .insert({
        id: input.id,
        tenant_id: input.tenantId,
        started_at: input.startedAt,
        completed_at: input.completedAt,
        duration_ms: input.durationMs,
        total_verdicts: input.totalVerdicts,
        total_briefs_auto_generated: input.totalBriefsAutoGenerated,
        total_assets_generated: input.totalAssetsGenerated,
        total_campaigns_published: input.totalCampaignsPublished,
      })
      .select("*")
      .single();
    if (error !== null || data === null) {
      throw new LoopRunRepositoryError(
        `LoopRunRepository.insert failed: ${error?.message ?? "no row returned"}`,
      );
    }
    return data;
  }

  /** Newest-first — the real Loop Run summary list source. */
  async listForTenant(tenantId: string, limit = 50): Promise<readonly LoopRunRow[]> {
    const { data, error } = await this.client
      .from<LoopRunRow>(TABLE)
      .select("*")
      .eq("tenant_id", tenantId)
      .order("created_at", { ascending: false })
      .limit(limit);
    if (error !== null) {
      throw new LoopRunRepositoryError(`LoopRunRepository.listForTenant failed: ${error.message}`);
    }
    return data ?? [];
  }
}
