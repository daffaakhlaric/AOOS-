import { describe, expect, it } from "vitest";

import { InvalidSampleException } from "../../src/errors/invalid-sample-exception.js";
import { CollectMetricsStage } from "../../src/pipeline/stages/collect-metrics-stage.js";
import { GenerateReportsStage } from "../../src/pipeline/stages/generate-reports-stage.js";
import { KnowledgeReportType } from "../../src/types/report-type.js";
import { createPipelineContextFixture } from "../helpers/pipeline-context-fixture.js";

describe("GenerateReportsStage", () => {
  it("throws InvalidSampleException when `collected` has not been populated yet", () => {
    const context = { ...createPipelineContextFixture(), runId: "run_1" };
    expect(() => new GenerateReportsStage().execute(context)).toThrow(InvalidSampleException);
  });

  it("generates a Summary report plus one report per single-domain type (9 total)", () => {
    let context = { ...createPipelineContextFixture(), runId: "run_1" };
    context = new CollectMetricsStage().execute(context);
    const result = new GenerateReportsStage().execute(context);
    expect(result.reports).toHaveLength(9);
    const types = result.reports!.map((r) => r.type);
    expect(types).toContain(KnowledgeReportType.Summary);
    expect(types).toContain(KnowledgeReportType.Usage);
    expect(types).toContain(KnowledgeReportType.Recommendation);
  });

  it("adds every generated report to the report registry", () => {
    let context = { ...createPipelineContextFixture(), runId: "run_1" };
    context = new CollectMetricsStage().execute(context);
    const result = new GenerateReportsStage().execute(context);
    for (const report of result.reports!) {
      expect(context.reportRegistry.has(report.id)).toBe(true);
    }
  });

  it("increments statistics.reportsGenerated by the number of reports produced", () => {
    let context = { ...createPipelineContextFixture(), runId: "run_1" };
    context = new CollectMetricsStage().execute(context);
    new GenerateReportsStage().execute(context);
    expect(context.statistics.snapshot(0).reportsGenerated).toBe(9);
  });

  it("populates the Usage report with the usage section content", () => {
    const fixture = createPipelineContextFixture();
    fixture.analytics.usage.recordDocumentAdded(7);
    let context = { ...fixture, runId: "run_1" };
    context = new CollectMetricsStage().execute(context);
    const result = new GenerateReportsStage().execute(context);
    const usageReport = result.reports!.find((r) => r.type === KnowledgeReportType.Usage)!;
    expect((usageReport.sections.usage as { documentCount: number }).documentCount).toBe(7);
  });

  it("resets the builder before assembling reports (no leakage from a prior manual build)", () => {
    let context = { ...createPipelineContextFixture(), runId: "run_1" };
    context.reportBuilder.withUsage({ stale: true });
    context = new CollectMetricsStage().execute(context);
    const result = new GenerateReportsStage().execute(context);
    const usageReport = result.reports!.find((r) => r.type === KnowledgeReportType.Usage)!;
    expect(usageReport.sections.usage).not.toEqual({ stale: true });
  });
});
