import { describe, expect, it, vi } from "vitest";

import type { IExternalMetricsSink } from "../../src/contracts/i-external-metrics-sink.js";
import { ReportNotFoundException } from "../../src/errors/report-not-found-exception.js";
import { KnowledgeAnalyticsEngine } from "../../src/services/knowledge-analytics-engine.js";
import { KnowledgeReportType } from "../../src/types/report-type.js";
import { createFixedClock } from "../../src/utils/clock.js";
import { KnowledgeMetricSample } from "../../src/value-objects/knowledge-metric-sample.js";

describe("KnowledgeAnalyticsEngine.runPipeline", () => {
  it("runs the full pipeline and returns a populated context", () => {
    const engine = new KnowledgeAnalyticsEngine({ clock: createFixedClock(1000) });
    engine.usage.recordDocumentAdded(1);
    const result = engine.runPipeline();
    expect(result.collected).toBeDefined();
    expect(result.reports).toHaveLength(9);
    expect(result.dashboardSnapshot).toBeDefined();
  });

  it("caches the latest dashboard snapshot", () => {
    const engine = new KnowledgeAnalyticsEngine();
    engine.runPipeline();
    expect(engine.latestDashboard()).toBeDefined();
  });

  it("latestDashboard throws ReportNotFoundException before any pipeline run", () => {
    expect(() => new KnowledgeAnalyticsEngine().latestDashboard()).toThrow(ReportNotFoundException);
  });

  it("getReport retrieves a report generated by the pipeline", () => {
    const engine = new KnowledgeAnalyticsEngine();
    const result = engine.runPipeline();
    const usageReport = result.reports!.find((r) => r.type === KnowledgeReportType.Usage)!;
    expect(engine.getReport(usageReport.id)).toBe(usageReport);
  });

  it("includes trend series tracked via trackTrendSeries", () => {
    const engine = new KnowledgeAnalyticsEngine();
    engine.trackTrendSeries("search_count");
    engine.trend.recordHistoricalValue("search_count", 5);
    const result = engine.runPipeline();
    const trendSection = (result.collected as { trend: { series: Record<string, unknown> } }).trend;
    expect(trendSection.series).toHaveProperty("search_count");
  });

  it("supports running the pipeline multiple times", () => {
    const engine = new KnowledgeAnalyticsEngine();
    const first = engine.runPipeline();
    const second = engine.runPipeline();
    expect(first.runId).not.toBe(second.runId);
  });
});

describe("KnowledgeAnalyticsEngine.summary", () => {
  it("reports zero totals for a freshly constructed engine", () => {
    const engine = new KnowledgeAnalyticsEngine({ clock: createFixedClock(1000) });
    const summary = engine.summary();
    expect(summary.totalSamplesRecorded).toBe(0);
    expect(summary.totalReportsGenerated).toBe(0);
    expect(summary.totalMetricsTracked).toBeGreaterThan(0);
  });

  it("reflects recorded samples across services", () => {
    const engine = new KnowledgeAnalyticsEngine();
    engine.usage.recordDocumentAdded(1);
    engine.search.recordSearch({ hit: true });
    expect(engine.summary().totalSamplesRecorded).toBe(2);
  });

  it("reflects reports generated after a pipeline run", () => {
    const engine = new KnowledgeAnalyticsEngine();
    engine.runPipeline();
    expect(engine.summary().totalReportsGenerated).toBe(9);
  });

  it("breaks totals down per category", () => {
    const engine = new KnowledgeAnalyticsEngine();
    engine.usage.recordDocumentAdded(1);
    expect(engine.summary().categoryTotals.usage).toBe(1);
    expect(engine.summary().categoryTotals.search).toBe(0);
  });
});

describe("KnowledgeAnalyticsEngine external metrics sink", () => {
  it("forwards samples to the supplied sink", () => {
    const received: KnowledgeMetricSample[] = [];
    const sink: IExternalMetricsSink = { receive: (sample) => received.push(sample) };
    const engine = new KnowledgeAnalyticsEngine({ externalMetricsSink: sink });
    const sample = new KnowledgeMetricSample({ name: "x", value: 1, timestamp: 0 });
    engine.mirrorToExternalSink(sample);
    expect(received).toEqual([sample]);
  });

  it("does not throw when no sink was supplied", () => {
    const engine = new KnowledgeAnalyticsEngine();
    const sample = new KnowledgeMetricSample({ name: "x", value: 1, timestamp: 0 });
    expect(() => engine.mirrorToExternalSink(sample)).not.toThrow();
  });

  it("increments statistics.samplesRecorded when mirroring", () => {
    const engine = new KnowledgeAnalyticsEngine();
    const sample = new KnowledgeMetricSample({ name: "x", value: 1, timestamp: 0 });
    engine.mirrorToExternalSink(sample);
    expect(engine.statistics.snapshot(0).samplesRecorded).toBe(1);
  });
});

describe("KnowledgeAnalyticsEngine custom dependencies", () => {
  it("uses a custom event publisher when supplied", () => {
    const publish = vi.fn();
    const engine = new KnowledgeAnalyticsEngine({ eventPublisher: { publish } });
    engine.runPipeline();
    expect(publish).toHaveBeenCalled();
  });
});
