import { beforeEach, describe, expect, it } from "vitest";

import { KnowledgeUpdateReportBuilder } from "../../src/builders/knowledge-update-report-builder.js";
import { KnowledgeAutoUpdateEngine } from "../../src/services/knowledge-auto-update-engine.js";
import { ALL_REPORT_TYPES, KnowledgeUpdateReportType } from "../../src/types/report-type.js";
import { ScheduleKind } from "../../src/types/schedule-descriptor.js";
import { KnowledgeUpdateType } from "../../src/types/update-type.js";
import { ManualClock } from "../../src/utils/clock.js";
import { resetFixtureState } from "../helpers/fixtures.js";

function makeEngine() {
  const clock = new ManualClock(0);
  const engine = new KnowledgeAutoUpdateEngine({ clock });
  return { clock, engine };
}

describe("Metrics and reports integration", () => {
  beforeEach(resetFixtureState);

  it("accumulates update/success/failure counts across several ticks", () => {
    const { engine, clock } = makeEngine();
    engine.scheduleJob({ targetId: "t-1", updateType: KnowledgeUpdateType.Manual, payload: {} });
    engine.scheduleJob({ targetId: "t-2", updateType: KnowledgeUpdateType.Manual, payload: {} });
    engine.scheduleJob({ targetId: "t-3", updateType: KnowledgeUpdateType.Version, payload: {} }); // fails

    engine.tick(clock.now());

    const metrics = engine.getMetrics();
    expect(metrics.updateCount).toBe(3);
    expect(metrics.successCount).toBe(2);
    expect(metrics.failureCount).toBe(1);
    expect(metrics.successRate).toBeCloseTo(2 / 3);
    expect(metrics.failureRate).toBeCloseTo(1 / 3);
  });

  it("tracks completed/pending job counts and queue size across ticks", () => {
    const { engine, clock } = makeEngine();
    engine.scheduleJob({ targetId: "t-1", updateType: KnowledgeUpdateType.Manual, payload: {} });
    engine.scheduleJob({
      targetId: "t-2",
      updateType: KnowledgeUpdateType.Manual,
      payload: {},
      schedule: { kind: ScheduleKind.Scheduled, runAt: 1_000_000 }, // not due this tick
    });
    engine.tick(clock.now());
    const metrics = engine.getMetrics();
    expect(metrics.completedJobs).toBe(1);
    expect(metrics.pendingJobs).toBe(1);
    expect(metrics.queueSize).toBe(1);
  });

  it("tracks retry counts via engine metrics after a failed attempt", () => {
    const { engine, clock } = makeEngine();
    const policy = engine.registerPolicy({
      name: "retry-metrics",
      maxRetries: 2,
      retryDelayMs: 10,
    });
    engine.scheduleJob({
      targetId: "t-1",
      policyId: policy.id,
      updateType: KnowledgeUpdateType.Version,
      payload: {},
    });
    engine.tick(clock.now());
    expect(engine.getMetrics().retryCount).toBe(1);
    expect(engine.getMetrics().retryRate).toBeCloseTo(1);
  });

  it("tracks cancelled job counts", () => {
    const { engine } = makeEngine();
    const job = engine.scheduleJob({
      targetId: "t-1",
      updateType: KnowledgeUpdateType.Manual,
      payload: {},
    });
    engine.cancelJob(job.id);
    expect(engine.getMetrics().cancelledJobs).toBe(1);
  });

  it("tracks expired job counts after expireStaleJobs", () => {
    const { engine, clock } = makeEngine();
    const policy = engine.registerPolicy({ name: "expires-fast", expireAfterMs: 1 });
    engine.scheduleJob({
      targetId: "t-1",
      policyId: policy.id,
      updateType: KnowledgeUpdateType.Manual,
      payload: {},
      schedule: { kind: ScheduleKind.Scheduled, runAt: 1_000_000 },
    });
    clock.set(1000);
    engine.expireStaleJobs(clock.now());
    expect(engine.getMetrics().expiredJobs).toBe(1);
  });

  it("computes average update time from durations recorded during execution", () => {
    const { engine, clock } = makeEngine();
    engine.scheduleJob({ targetId: "t-1", updateType: KnowledgeUpdateType.Manual, payload: {} });
    engine.tick(clock.now());
    // Every strategy execution is synchronous/instantaneous in this deterministic package, so
    // durations are always 0 — but the metric must still compute (not NaN/undefined).
    expect(engine.getMetrics().averageUpdateTimeMs).toBe(0);
  });

  describe.each(ALL_REPORT_TYPES)("report type: %s", (type) => {
    it("can be built by KnowledgeUpdateReportBuilder from arbitrary engine-derived data", () => {
      const { engine, clock } = makeEngine();
      engine.scheduleJob({ targetId: "t-1", updateType: KnowledgeUpdateType.Manual, payload: {} });
      engine.tick(clock.now());
      const metrics = engine.getMetrics();
      const report = new KnowledgeUpdateReportBuilder()
        .ofType(type)
        .withData({ metrics })
        .build(clock.now());
      expect(report.type).toBe(type);
      expect(report.data.metrics).toEqual(metrics);
    });
  });

  it("UpdateSummary reports are auto-generated by the pipeline for every ticked job", () => {
    const { engine, clock } = makeEngine();
    engine.scheduleJob({ targetId: "t-1", updateType: KnowledgeUpdateType.Manual, payload: {} });
    engine.scheduleJob({ targetId: "t-2", updateType: KnowledgeUpdateType.Manual, payload: {} });
    engine.tick(clock.now());
    // Access via a fresh report builder is not how the pipeline stores reports; verify indirectly
    // through the snapshot's completed count instead (reports themselves are registry-internal).
    expect(engine.getSnapshot().completedJobCount).toBe(2);
  });

  it("KnowledgeUpdateReportType has exactly 10 members and no duplicates", () => {
    const values = Object.values(KnowledgeUpdateReportType);
    expect(values).toHaveLength(10);
    expect(new Set(values).size).toBe(10);
  });
});
